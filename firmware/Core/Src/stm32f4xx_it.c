/**
 * @brief This function handles EXTI line[15:10] interrupts.
 */
void EXTI15_10_IRQHandler(void) {
	/* USER CODE BEGIN EXTI15_10_IRQn 0 */

	/* USER CODE END EXTI15_10_IRQn 0 */
	/* If VSYNC rising and HREF rising become pending together at frame start,
	 * activate the frame state before processing the first HREF line. At frame
	 * end, keep HREF-first ordering so a coincident final line is finalized
	 * before VSYNC closes the frame. */
	if (((EXTI->PR & CAM_VSYNC_Pin) != 0U)
			&& (HAL_GPIO_ReadPin(CAM_VSYNC_GPIO_Port, CAM_VSYNC_Pin)
					== GPIO_PIN_SET)) {
		HAL_GPIO_EXTI_IRQHandler(CAM_VSYNC_Pin);
		HAL_GPIO_EXTI_IRQHandler(CAM_HREF_Pin);
	} else {
		HAL_GPIO_EXTI_IRQHandler(CAM_HREF_Pin);
		HAL_GPIO_EXTI_IRQHandler(CAM_VSYNC_Pin);
	}
	/* USER CODE BEGIN EXTI15_10_IRQn 1 */

	/* USER CODE END EXTI15_10_IRQn 1 */
}

